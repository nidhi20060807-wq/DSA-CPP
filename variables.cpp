
#include <iostream>
#include <string>
using namespace std;

int main()
{
    // Integer variable
    int age = 20;

    // Decimal variable
    float marks = 95.5;

    // Character variable
    char grade = 'A';

    // String variable
    string name = "Student";

    // Boolean variable
    bool isLearning = true;

    cout << "Name: " << name << endl;
    cout << "Age: " << age << endl;
    cout << "Marks: " << marks << endl;
    cout << "Grade: " << grade << endl;
    cout << "Learning: " << isLearning << endl;

    return 0;
}
